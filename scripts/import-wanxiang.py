#!/usr/bin/env python3
"""Pinned Wanxiang import. Default is fully offline; --fetch downloads the locked sources."""
import argparse
from concurrent.futures import ThreadPoolExecutor
import hashlib
import json
from pathlib import Path
import re
import unicodedata
import urllib.request

REVISION = "b582a1b2a623a0da2d31729226224fd948e1c735"
ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "assets/rime/wanxiang_source"
RUNTIME = ROOT / "assets/rime/full_pinyin"
BASE_URL = f"https://raw.githubusercontent.com/amzxyz/rime-wanxiang/{REVISION}/"

def normalize_reading(reading):
    reading = unicodedata.normalize("NFC", reading).lower().translate(str.maketrans({c: "v" for c in "üǖǘǚǜ"}))
    reading = "".join(c for c in unicodedata.normalize("NFD", reading) if unicodedata.category(c) != "Mn")
    reading = " ".join(reading.split())
    if not re.fullmatch(r"[a-z]+(?: [a-z]+)*", reading):
        raise ValueError(f"unsupported pinyin: {reading!r}")
    return reading

def read_records(path):
    started = False
    for number, line in enumerate(path.read_text(encoding="utf-8", errors="strict").splitlines(), 1):
        if line.strip() == "...": started = True; continue
        if not started or not line or line.startswith("#"): continue
        fields = line.split("\t")
        if len(fields) == 4: fields = fields[:3]  # Upstream cuoyin annotation is Lua-only.
        if len(fields) == 2: fields.append("1")
        # This single typo is present in the pinned upstream poem table. Keep
        # the phrase at minimum weight; reject any other malformed frequency.
        if (path.name == "shici.dict.yaml" and fields ==
            ["宜乎百姓之谓我爱也", "yí hū bǎi xìng zhī wèi wǒ ài yě", "10s"]): fields[2] = "1"
        if len(fields) != 3 or not fields[0] or not re.fullmatch(r"-?[0-9]+", fields[2]):
            raise ValueError(f"{path.name}:{number}: invalid record")
        weight = int(fields[2])
        if any(ord(c) < 32 for c in fields[0]): raise ValueError(f"{path.name}:{number}: control character")
        yield fields[0], fields[1], weight
    if not started: raise ValueError(f"{path}: missing dictionary marker")

def merge_records(records):
    merged = {}
    for text, reading, weight in records:
        weight = max(1, weight)
        key = (text, normalize_reading(reading))
        merged[key] = max(weight, merged.get(key, 0))
    return merged

def dictionary_bytes(name, entries):
    header = f"# Generated by scripts/import-wanxiang.py; original data: amzxyz/rime-wanxiang (CC-BY-4.0).\n# Pinyin tones normalized; duplicate text/reading uses maximum original weight.\n---\nname: {name}\nversion: \"{REVISION[:12]}\"\nsort: by_weight\nuse_preset_vocabulary: false\n...\n"
    return (header + "".join(f"{text}\t{reading}\t{weight}\n" for (text, reading), weight in sorted(entries.items()))).encode("utf-8")

def fetch(relative):
    request = urllib.request.Request(BASE_URL + relative, headers={"User-Agent": "ZhixuIME-pinned-assets"})
    data = urllib.request.urlopen(request, timeout=90).read()
    data.decode("utf-8", errors="strict")
    path = SOURCE / relative
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_suffix(path.suffix + ".tmp")
    temporary.write_bytes(data); temporary.replace(path)
    return relative

def run(fetch_sources=False, check=False):
    if fetch_sources:
        for relative in ("wanxiang.dict.yaml", "LICENSE"): fetch(relative)
    main = (SOURCE / "wanxiang.dict.yaml").read_text(encoding="utf-8")
    tables = re.findall(r"^\s*-\s*(dicts/[a-z_]+)\s*(?:#.*)?$", main, re.M)
    if not tables or len(tables) != len(set(tables)): raise ValueError("invalid import table list")
    source_files = [table + ".dict.yaml" for table in tables]
    if fetch_sources:
        with ThreadPoolExecutor(max_workers=3) as pool: list(pool.map(fetch, source_files))
    merged = {}; counts = {}; source_records = 0
    for relative in source_files:
        rows = list(read_records(SOURCE / relative)); counts[relative] = len(rows); source_records += len(rows)
        if not rows: raise ValueError(f"empty source dictionary: {relative}")
        for key, weight in merge_records(rows).items(): merged[key] = max(weight, merged.get(key, 0))
    # Preserve curated source separately, so regeneration cannot accumulate edits.
    original_daily = SOURCE / "zhixu_daily.original.dict.yaml"
    if not original_daily.exists():
        if check: raise ValueError("original supplement source missing")
        original_daily.write_bytes((RUNTIME / "zhixu_daily.dict.yaml").read_bytes())
    daily = {key: 1 for key in merge_records(read_records(original_daily)) if key not in merged}
    generated = {"wanxiang_plain.dict.yaml": dictionary_bytes("wanxiang_plain", merged),
                 "zhixu_daily.dict.yaml": dictionary_bytes("zhixu_daily", daily),
                 "WANXIANG-LICENSE": (SOURCE / "LICENSE").read_bytes(),
                 "WANXIANG-ATTRIBUTION.txt": ("Wanxiang dictionary by amzxyz and contributors\nSource: https://github.com/amzxyz/rime-wanxiang\nRevision: " + REVISION + "\nLicense: Creative Commons Attribution 4.0 International (CC-BY-4.0)\nChanges: stripped pinyin tone marks, mapped umlaut to v, merged duplicate text/reading with maximum weight.\nCurated Zhixu supplement contains only absent entries, weight 1. Original sources remain under assets/rime/wanxiang_source.\n").encode("utf-8")}
    if check:
        for name, data in generated.items():
            if (RUNTIME / name).read_bytes() != data: raise ValueError(f"nonreproducible asset: {name}")
    else:
        for name, data in generated.items():
            temporary = RUNTIME / (name + ".tmp"); temporary.write_bytes(data); temporary.replace(RUNTIME / name)
    paths = [SOURCE / relative for relative in ["wanxiang.dict.yaml", "LICENSE", *source_files, "zhixu_daily.original.dict.yaml"]]
    paths += [RUNTIME / name for name in generated]
    files = []
    for path in paths:
        relative = path.relative_to(ROOT).as_posix()
        record = {"path": relative, "sha256": hashlib.sha256(path.read_bytes()).hexdigest()}
        if path.parent == SOURCE or SOURCE in path.parents:
            source_relative = path.relative_to(SOURCE).as_posix()
            if source_relative != "zhixu_daily.original.dict.yaml": record["source"] = BASE_URL + source_relative
        else: record["generated"] = True
        files.append(record)
    lock_path = ROOT / "third_party.lock.json"
    lock = json.loads(lock_path.read_text(encoding="utf-8"))
    asset = {"name": "rime-wanxiang", "source": "https://github.com/amzxyz/rime-wanxiang", "revision": REVISION,
             "license": "CC-BY-4.0", "usage": "built-in full-Pinyin dictionary", "files": files,
             "notes": "All Chinese import tables; no Lua or grammar model. Reproduce offline with scripts/import-wanxiang.py --check."}
    if check:
        old = next(a for a in lock["assets"] if a["name"] == "rime-wanxiang")
        if old != asset: raise ValueError("asset manifest mismatch")
    else:
        lock["assets"] = [a for a in lock["assets"] if a["name"] != "rime-wanxiang"] + [asset]
        lock_path.write_text(json.dumps(lock, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    report = {"revision": REVISION, "tables": len(tables), "source_records": source_records,
              "normalized_records": len(merged), "supplement_records": len(daily), "source_counts": counts,
              "dictionary_bytes": len(generated["wanxiang_plain.dict.yaml"]), "validation": "PASS"}
    print(json.dumps(report, ensure_ascii=False, indent=2))
    return report

if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--fetch", action="store_true")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    if args.fetch and args.check: parser.error("--check must be offline")
    run(args.fetch, args.check)
